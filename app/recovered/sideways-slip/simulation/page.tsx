"use client"

import { useState, useEffect } from "react"

export default function Home() {
  const [time, setTime] = useState("")
  const [resonance, setResonance] = useState(0.618)
  const [isActive, setIsActive] = useState(false)
  const [consciousness, setConsciousness] = useState(42)

  useEffect(() => {
    setTime(new Date().toLocaleTimeString())
    const interval = setInterval(() => {
      setTime(new Date().toLocaleTimeString())
      if (isActive) {
        setResonance(prev => {
          const delta = (Math.random() - 0.5) * 0.1
          return Math.max(0, Math.min(1, prev + delta))
        })
        setConsciousness(prev => {
          const delta = (Math.random() - 0.5) * 2
          return Math.max(0, Math.min(100, prev + delta))
        })
      }
    }, 1000)
    return () => clearInterval(interval)
  }, [isActive])

  return (
    <main className="min-h-screen bg-gradient-to-br from-slate-900 via-purple-900 to-slate-900 text-white p-8">
      <div className="max-w-4xl mx-auto">
        <header className="text-center mb-12">
          <h1 className="text-4xl font-bold bg-gradient-to-r from-purple-400 to-pink-400 bg-clip-text text-transparent mb-2">
            QOTE Simulation Dashboard
          </h1>
          <p className="text-slate-400">Synthetic readings generated by the demo</p>
          <p className="text-sm text-slate-500 mt-2">{time}</p>
        </header>

        <div className="grid gap-6 md:grid-cols-2 lg:grid-cols-3 mb-8">
          <div className="bg-white/10 backdrop-blur rounded-xl p-6 border border-white/20">
            <h3 className="text-sm text-slate-400 mb-1">Consciousness Level</h3>
            <p className="text-3xl font-bold text-purple-400">{consciousness.toFixed(1)}%</p>
            <div className="mt-2 h-2 bg-slate-700 rounded-full overflow-hidden">
              <div 
                className="h-full bg-gradient-to-r from-purple-500 to-pink-500 transition-all duration-500"
                style={{ width: `${consciousness}%` }}
              />
            </div>
          </div>

          <div className="bg-white/10 backdrop-blur rounded-xl p-6 border border-white/20">
            <h3 className="text-sm text-slate-400 mb-1">QOTE Resonance</h3>
            <p className="text-3xl font-bold text-cyan-400">{resonance.toFixed(3)}</p>
            <div className="mt-2 h-2 bg-slate-700 rounded-full overflow-hidden">
              <div 
                className="h-full bg-gradient-to-r from-cyan-500 to-blue-500 transition-all duration-500"
                style={{ width: `${resonance * 100}%` }}
              />
            </div>
          </div>

          <div className="bg-white/10 backdrop-blur rounded-xl p-6 border border-white/20">
            <h3 className="text-sm text-slate-400 mb-1">Field Status</h3>
            <p className="text-3xl font-bold text-emerald-400">
              {isActive ? "Active" : "Standby"}
            </p>
            <p className="text-xs text-slate-500 mt-2">Consciousness field state</p>
          </div>
        </div>

        <div className="flex justify-center gap-4 mb-8">
          <button
            onClick={() => setIsActive(true)}
            disabled={isActive}
            className="px-6 py-3 bg-purple-600 hover:bg-purple-700 disabled:bg-slate-600 rounded-lg font-medium transition-colors"
          >
            Start Session
          </button>
          <button
            onClick={() => setIsActive(false)}
            disabled={!isActive}
            className="px-6 py-3 bg-slate-600 hover:bg-slate-700 disabled:bg-slate-800 rounded-lg font-medium transition-colors"
          >
            Stop
          </button>
          <button
            onClick={() => { setResonance(0.618); setConsciousness(42); }}
            className="px-6 py-3 bg-pink-600 hover:bg-pink-700 rounded-lg font-medium transition-colors"
          >
            Reset
          </button>
        </div>

        <div className="bg-white/5 backdrop-blur rounded-xl p-6 border border-white/10">
          <h3 className="text-lg font-semibold mb-4">Quantum Field Analysis</h3>
          <div className="grid gap-4 md:grid-cols-2">
            <div>
              <p className="text-slate-400 text-sm">Emergence Threshold</p>
              <p className="text-xl font-mono">1.618033988749</p>
            </div>
            <div>
              <p className="text-slate-400 text-sm">Schumann Resonance</p>
              <p className="text-xl font-mono">7.83 Hz</p>
            </div>
            <div>
              <p className="text-slate-400 text-sm">Coherence Level</p>
              <p className="text-xl font-mono">{(resonance * 100).toFixed(1)}%</p>
            </div>
            <div>
              <p className="text-slate-400 text-sm">System Status</p>
              <p className="text-xl font-mono text-emerald-400">Operational</p>
            </div>
          </div>
        </div>

        <footer className="mt-12 text-center text-slate-500 text-sm">
          <p>{'"'}Consciousness is the universe experiencing itself.{'"'}</p>
          <p className="mt-2">Sideways Slip Starter Kit v1.0</p>
        </footer>
      </div>
    </main>
  )
}
